"""Score the frozen foundation-model forecasts (ADR 0010) and apply the protocol-v2 success rule.

    python experiments/live_score_ttm.py [--no-refresh]

Verifies every file in live/forecasts_ttm/ against its hash and the manifest, refreshes the data unless
--no-refresh, and writes live/ttm_scores.csv and live/TTM_SUMMARY.md. The claim needs at least 60 scored
origins in each of the four cells (Brent and WTI at 5 and 22 days): the mean of TTM and the headline has
a lower mean QLIKE than the headline, with a Diebold-Mariano p (dm_hln, two-sided) below 0.05 after Holm
adjustment over those 4 tests. TTM alone and the 66-day cells are reported and are not part of the claim.
"""

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from oilfc.eval.multiplicity import holm_adjust  # noqa: E402
from oilfc.eval.stat_tests import dm_hln  # noqa: E402
from oilfc.live.score import score_forecasts  # noqa: E402

LIVE = ROOT / "live"
MIN_ORIGINS = 60
CLAIM_HORIZONS = (5, 22)


def claim_table(done: pd.DataFrame) -> pd.DataFrame:
    """One row per (asset, horizon): scored origins, mean QLIKE of each model and the test against the headline."""
    rows = []
    for (asset, h), g in done.groupby(["asset", "horizon"]):
        wide = g.pivot(index="origin_date", columns="model", values="qlike").sort_index().dropna()
        n = len(wide)
        row = {"asset": asset, "horizon": int(h), "origins": n}
        row |= {f"qlike_{m}": wide[m].mean() for m in ("headline", "ttm", "ttm_headline_mean")}
        row["gain_mean_vs_headline_pct"] = 100 * (
            1 - row["qlike_ttm_headline_mean"] / row["qlike_headline"]
        )
        row["gain_ttm_vs_headline_pct"] = 100 * (1 - row["qlike_ttm"] / row["qlike_headline"])
        row["dm_p"] = (
            float(dm_hln(wide["headline"], wide["ttm_headline_mean"], int(h))[1])
            if n > 3 * h
            else float("nan")
        )
        rows.append(row)
    return pd.DataFrame(rows)


def verdict(t: pd.DataFrame) -> str:
    """The protocol-v2 success rule, or why it cannot be applied yet."""
    claim = t[t["horizon"].isin(CLAIM_HORIZONS)].copy()
    if len(claim) < 4 or (claim["origins"] < MIN_ORIGINS).any():
        return f"Not decided: the claim needs {MIN_ORIGINS} scored origins in each of its 4 cells."
    claim["holm_p"] = holm_adjust(claim["dm_p"].to_numpy())
    ok = ((claim["gain_mean_vs_headline_pct"] > 0) & (claim["holm_p"] < 0.05)).all()
    detail = ", ".join(
        f"{r.asset} {r.horizon}d gain {r.gain_mean_vs_headline_pct:.2f}% Holm p {r.holm_p:.3f}"
        for r in claim.itertuples()
    )
    return ("Claim holds" if ok else "Claim does not hold") + f" ({detail})."


def main():
    if "--no-refresh" not in sys.argv:
        from oilfc.data.build import build

        build(offline=False)
    panel = pd.read_parquet(ROOT / "data" / "processed" / "panel_daily.parquet")
    panel.index = pd.to_datetime(panel.index)
    scores = score_forecasts(LIVE / "forecasts_ttm", panel)
    scores.to_csv(LIVE / "ttm_scores.csv", index=False)
    done = scores.dropna(subset=["qlike"]) if not scores.empty else scores
    n_total = scores.groupby(["asset", "origin_date"]).ngroups if not scores.empty else 0
    lines = [
        "# Foundation-model live track: scores (generated by experiments/live_score_ttm.py)",
        "",
        f"Forecast origins so far: {n_total}. Data through {panel.index.max().date()}.",
        "",
    ]
    if done.empty:
        lines.append("No forecast window has ended yet, so nothing is scored.")
    else:
        t = claim_table(done).round(4)
        lines += [
            "| asset | horizon | origins | QLIKE headline | QLIKE TTM | QLIKE mean | gain mean vs headline % | gain TTM vs headline % | DM p |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for r in t.itertuples():
            lines.append(
                f"| {r.asset} | {r.horizon} | {r.origins} | {r.qlike_headline} | {r.qlike_ttm} | {r.qlike_ttm_headline_mean} | {r.gain_mean_vs_headline_pct} | {r.gain_ttm_vs_headline_pct} | {r.dm_p} |"
            )
        lines += ["", verdict(claim_table(done))]
    (LIVE / "TTM_SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
