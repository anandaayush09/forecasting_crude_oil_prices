"""Score the frozen live forecasts against realised volatility, for every origin whose window has ended.

    .venv/Scripts/python.exe experiments/live_score.py [--no-refresh]

Verifies every forecast file against its stored hash and the manifest (stops if one fails), refreshes
the data unless --no-refresh, and writes live/scores.csv (all rows) and live/SUMMARY.md (mean QLIKE
and gain over naive per asset, horizon and model, scored origins only).
"""

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from oilfc.live.score import score_forecasts  # noqa: E402

LIVE = ROOT / "live"


def main():
    if "--no-refresh" not in sys.argv:
        from oilfc.data.build import build

        build(offline=False)
    panel = pd.read_parquet(ROOT / "data" / "processed" / "panel_daily.parquet")
    panel.index = pd.to_datetime(panel.index)
    scores = score_forecasts(LIVE / "forecasts", panel)
    scores.to_csv(LIVE / "scores.csv", index=False)
    done = scores.dropna(subset=["qlike"])
    n_total = scores.groupby(["asset", "origin_date"]).ngroups
    lines = [
        "# Live forward test: scores (generated by experiments/live_score.py)",
        "",
        f"Forecast origins so far: {n_total}. Data through {panel.index.max().date()}.",
        "",
    ]
    if done.empty:
        lines.append("No forecast window has ended yet, so nothing is scored.")
    else:
        g = done.groupby(["asset", "horizon", "model"])
        t = g.agg(origins=("qlike", "size"), mean_qlike=("qlike", "mean"))
        naive = t.xs("naive", level="model")["mean_qlike"]
        t["gain_vs_naive_pct"] = [
            100 * (1 - row.mean_qlike / naive[(a, h)]) for (a, h, _), row in t.iterrows()
        ]
        t = t.round(4).reset_index()
        lines += [
            "| asset | horizon | model | origins | mean QLIKE | gain vs naive % |",
            "|---|---|---|---|---|---|",
        ]
        for r in t.itertuples():
            lines.append(
                f"| {r.asset} | {r.horizon} | {r.model} | {r.origins} | {r.mean_qlike} | {r.gain_vs_naive_pct} |"
            )
        lines += [
            "",
            "Few origins and overlapping windows: no significance test is meaningful before roughly 60 origins per horizon.",
        ]
    (LIVE / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"{len(done)} scored rows of {len(scores)}")


if __name__ == "__main__":
    main()
